export function chileCompanyLabel(n: number) {
  return `${n}ª Compañía`;
}

export function chileInstitution(cuerpoName: string) {
  return `Bomberos de ${cuerpoName}`;
}

export function chileUnitsForCompany(regionName: string, companyNumber: number) {
  const units = CHILE_UNIT_TYPES.map((item) => ({
    label: `${item.prefix}-${companyNumber}`,
    type: item.type,
    staffing: item.staffing,
  }));
  if (FORESTAL_REGIONS.has(regionName) && companyNumber === 1) {
    units.push({ label: 'F-1', type: 'Forestal', staffing: 4 });
  }
  return units;
}

export function chileCatalogTotals() {
  const cuerpos = CHILE_REGIONS.reduce((sum, region) => sum + region.cuerpos.length, 0);
  const companies = CHILE_REGIONS.reduce(
    (sum, region) => sum + region.cuerpos.reduce((acc, cuerpo) => acc + cuerpo.companies, 0),
    0,
  );
  return { cuerpos, companies, regions: CHILE_REGIONS.length };
}

export function chileResourceKey(institution: string, label: string) {
  return `${institution}|${label}`.toLowerCase();
}
